#!/usr/bin/env python3
"""Builds export/web/mods/prestige/camo-table.js: every gun with camos gets its own prestige camo set (Phase 4).

Input: .tools/prestige-guns.json, a list of {id, name, cls} (dump it from a match: every weapon with a Gunsmith,
see docs/fork/weapon-levels.md). Per gun: a hue spread by the golden angle over the whole list (so no two guns sit
close), a second hue, one style per tier (6 per tier; within a class the styles step so neighbours differ, and the
three tiers use different strides), and three names that are unique across every gun. Re-run after adding guns;
existing guns keep their entries unless the list order changes, so append new guns at the end of the JSON."""
import json, random, os
here=os.path.dirname(os.path.abspath(__file__))
guns=json.load(open(os.path.join(here,'prestige-guns.json')))
STYLES={1:['shards','chevrons','splinter','contour','scales','brush'],2:['lattice','filigree','damascus','mosaic','carbon','facets'],3:['cracks','circuit','runes','lightning','magma','constellation']}
ADJ={1:['Ashen','Cobalt','Feral','Hollow','Jagged','Molten','Phantom','Shattered','Venom','Wraith','Scarlet','Iron','Rusted','Savage','Crimson','Storm','Bone','Night','Ember','Frost','Toxic','Grave','Wild','Rogue'],
     2:['Gilded','Regal','Sovereign','Obsidian','Crowned','Imperial','Royal','Burnished','Ornate','Gleaming','Noble','Opal','Ivory','Sterling','Sacred','Velvet','Marble','Golden','Jeweled','Lustrous'],
     3:['Eternal','Undying','Ascendant','Abyssal','Celestial','Infernal','Astral','Void','Mythic','Arcane','Spectral','Primal','Radiant','Ethereal','Cosmic','Fabled','Hallowed','Omen','Rift','Aether']}
NOUN={1:['Fang','Shard','Rift','Talon','Scale','Husk','Ember','Spine','Claw','Splinter','Stripe','Tide'],2:['Lattice','Hive','Mosaic','Plate','Crest','Aegis','Filigree','Relic','Facet','Weave','Seal','Crown'],
      3:['Pulse','Nova','Current','Wake','Flux','Storm','Requiem','Surge','Zenith','Eclipse','Vortex','Halo']}
CLS_NOUN={'sniper':['Gaze','Sightline','Hawk'],'shotgun':['Scatter','Buckshot','Breach'],'smg':['Swarm','Rattle','Rush'],'ar':['Vanguard','March','Volley'],'lmg':['Barrage','Bulwark','Belt'],
          'pistol':['Sidearm','Duel','Draw'],'launcher':['Blast','Payload','Salvo'],'special':['Relic','Oddity','Wonder']}
GOLD=137.50776
order={c:i for i,c in enumerate(['ar','smg','lmg','sniper','shotgun','pistol','launcher','special'])}
used=set();table={};combos=set();tier_use={t:{} for t in (1,2,3)};cls_use={}
for i,g in enumerate(guns):
  cls=g.get('cls','special')
  # hues: pure golden angle over the list (the most even spread n points can have); h2 a contrasting second hue
  h=round((i*GOLD)%360,1);h2=round((h+140+(i%5)*22)%360,1)
  # styles: a triple no other gun has, preferring the styles least used so far in this gun's class, then overall
  cu=cls_use.setdefault(cls,{t:{} for t in (1,2,3)});r=random.Random('styles'+g['id'])
  cand=[(a,b,c) for a in STYLES[1] for b in STYLES[2] for c in STYLES[3] if (a,b,c) not in combos]
  def cost(t):return sum(cu[x+1].get(t[x],0)*10+tier_use[x+1].get(t[x],0) for x in range(3))+r.random()*.5
  best=min(cand,key=cost);combos.add(best)
  for x in range(3):cu[x+1][best[x]]=cu[x+1].get(best[x],0)+1;tier_use[x+1][best[x]]=tier_use[x+1].get(best[x],0)+1
  styles=list(best)
  r=random.Random(g['id']);names=[]
  for t in (1,2,3):
    for _ in range(400):
      noun=r.choice(CLS_NOUN.get(cls,[])+NOUN[t]) if r.random()<.35 else r.choice(NOUN[t])
      n=r.choice(ADJ[t])+' '+noun
      if n not in used:used.add(n);names.append(n);break
  table[g['id']]={'cls':cls,'h':h,'h2':h2,'styles':styles,'names':names}
out=os.path.join(here,'..','export','web','mods','prestige','camo-table.js')
with open(out,'w') as f:
  f.write('// Generated by .tools/build-prestige-camos.py: each gun with camos gets its own prestige camo set (hues spread by the\n// golden angle, one of 6 styles per tier, unique names). Guns missing here fall back to a hash of their id (camo.js).\n')
  f.write('export const PRESTIGE_TABLE='+json.dumps(table,separators=(',',':'))+';\n')
print(len(table),'guns;',len(used),'names')
